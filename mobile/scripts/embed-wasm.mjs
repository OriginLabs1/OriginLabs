// Embed the Rust core as base64 so the PWA and the Android file:// WebView can
// instantiate it without fetch(), CORS or a network. Also records the digest.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, "..");
const wasmPath = path.resolve(mobile, "build/origin_core.wasm");
const outPath = path.resolve(mobile, "web/wasm.js");
const rawOut = path.resolve(mobile, "web/origin_core.wasm");
const metaOut = path.resolve(mobile, "web/data/core.json");

if (!fs.existsSync(wasmPath)) {
  console.error(`Missing ${wasmPath}. Run scripts/build-wasm.sh first.`);
  process.exit(1);
}

const bytes = fs.readFileSync(wasmPath);
const digest = crypto.createHash("sha256").update(bytes).digest("hex");
const b64 = bytes.toString("base64");

const meta = {
  schema: "origin.core/v1",
  version: "0.0.1",
  engine: "rust",
  target: "wasm32-unknown-unknown",
  sha256: digest,
  bytes: bytes.length,
};
const banner = `/* Generated by scripts/embed-wasm.mjs — do not edit. sha256=${digest} */\n`;
fs.writeFileSync(
  outPath,
  `${banner}window.ORIGIN_CORE_META = ${JSON.stringify(meta)};\nwindow.ORIGIN_WASM_BASE64 = ${JSON.stringify(b64)};\n`,
);
fs.writeFileSync(rawOut, bytes);
fs.writeFileSync(
  metaOut,
  JSON.stringify(
    {
      ...meta,
      exportedFunctions: [
        "origin_alloc",
        "origin_free",
        "origin_result_len",
        "origin_sha256_hex",
        "origin_canonicalize",
        "origin_build_event",
        "origin_verify",
        "origin_self_test",
        "origin_version",
      ],
    },
    null,
    2,
  ) + "\n",
);

console.log(`Embedded Rust core: ${bytes.length} bytes, sha256 ${digest}`);
