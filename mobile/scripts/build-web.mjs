// Assemble the deployable web surface:
//   * embed the root registry snapshot (JSON + classic-script global),
//   * record build metadata,
//   * copy web/ into the Android assets and the Pages site,
//   * write a hashed asset manifest.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, "..");
const project = path.resolve(mobile, "..");
const web = path.resolve(mobile, "web");
const assetsRoot = path.resolve(mobile, "app/src/main/assets");
const assets = path.resolve(assetsRoot, "www");
const site = path.resolve(mobile, "site/app");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function sha256File(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function walk(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, base));
    else out.push(path.relative(base, full).split(path.sep).join("/"));
  }
  return out.sort();
}

function copyDir(from, to) {
  fs.rmSync(to, { recursive: true, force: true });
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dst);
    else fs.copyFileSync(src, dst);
  }
}

// ---------------------------------------------------------------- registry

const registryIndex = readJson(path.resolve(project, "registry/index.json"));
const items = registryIndex.entries.map((entry) => {
  const record = readJson(path.resolve(project, "registry", entry.path));
  if (record.id !== entry.id) throw new Error(`registry id mismatch for ${entry.path}`);
  if (record.kind !== entry.kind) throw new Error(`registry kind mismatch for ${entry.path}`);
  return record;
});

for (const kind of ["skill", "tool", "workflow", "model"]) {
  const actual = items.filter((item) => item.kind === kind).length;
  const declared = registryIndex.counts[`${kind}s`];
  if (declared !== actual) {
    throw new Error(`${kind} count mismatch: index says ${declared}, files say ${actual}`);
  }
}

const registry = {
  schema: "origin.mobile.registry/v1",
  source: registryIndex.schema,
  version: registryIndex.version,
  generated: registryIndex.generated,
  policy: registryIndex.policy,
  counts: registryIndex.counts,
  items,
};

fs.mkdirSync(path.join(web, "data"), { recursive: true });
const registryJson = JSON.stringify(registry, null, 2) + "\n";
fs.writeFileSync(path.join(web, "data/registry.json"), registryJson);
fs.writeFileSync(
  path.join(web, "data/registry.js"),
  `/* Generated by scripts/build-web.mjs — do not edit. */\nwindow.ORIGIN_REGISTRY = ${JSON.stringify(registry)};\n`
);

// ------------------------------------------------------------------- build

const coreMetaPath = path.join(web, "data/core.json");
if (!fs.existsSync(coreMetaPath)) {
  throw new Error("Missing web/data/core.json. Run scripts/build-wasm.sh first.");
}
const coreMeta = readJson(coreMetaPath);
const generatedAt = process.env.SOURCE_DATE_EPOCH
  ? new Date(Number(process.env.SOURCE_DATE_EPOCH) * 1000).toISOString()
  : new Date().toISOString();

const build = {
  schema: "origin.mobile.build/v1",
  app: { name: "OriginLabs", version: "0.0.1", package: "com.oneorigin.labs" },
  generatedAt,
  core: {
    version: coreMeta.version,
    engine: coreMeta.engine,
    target: coreMeta.target,
    sha256: coreMeta.sha256,
    bytes: coreMeta.bytes,
  },
  registry: {
    version: registry.version,
    generated: registry.generated,
    counts: registry.counts,
    sha256: crypto.createHash("sha256").update(registryJson).digest("hex"),
  },
  privacy: {
    permissions: [],
    network: false,
    accounts: false,
    telemetry: false,
  },
};
fs.writeFileSync(path.join(web, "data/build.json"), JSON.stringify(build, null, 2) + "\n");
fs.writeFileSync(
  path.join(web, "data/build.js"),
  `/* Generated by scripts/build-web.mjs — do not edit. */\nwindow.ORIGIN_BUILD = ${JSON.stringify(build)};\n`
);

// -------------------------------------------------------------------- copy

copyDir(web, assets);
copyDir(web, site);

// ---------------------------------------------------------------- manifest

const files = walk(assets).filter((file) => file !== "asset-manifest.json");
const manifest = {
  schema: "origin.assets/v1",
  app: build.app,
  generatedAt,
  coreSha256: coreMeta.sha256,
  files: files.map((file) => {
    const full = path.join(assets, file);
    const stat = fs.statSync(full);
    return { path: file, bytes: stat.size, sha256: sha256File(full) };
  }),
};
const manifestText = JSON.stringify(manifest, null, 2) + "\n";
fs.writeFileSync(path.join(assets, "asset-manifest.json"), manifestText);
fs.writeFileSync(path.join(web, "asset-manifest.json"), manifestText);
fs.writeFileSync(path.join(site, "asset-manifest.json"), manifestText);

const total = manifest.files.reduce((sum, file) => sum + file.bytes, 0);
console.log(
  `Web built: ${manifest.files.length} files, ${(total / 1024).toFixed(1)} KB, ` +
    `${registry.items.length} registry entries, core ${coreMeta.sha256.slice(0, 12)}…`
);
console.log(`  assets: ${path.relative(mobile, assets)}`);
console.log(`  site:   ${path.relative(mobile, site)}`);
